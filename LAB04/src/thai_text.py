# thai_text.py
# การเตรียมข้อความภาษาไทยที่ใช้ร่วมกันทั้งตอนสร้าง index และตอนค้นหา
#
# ต้องเรียกจากทั้งสองฝั่งเสมอ ไม่งั้นข้อความในคลังกับคำค้นจะถูกจัดการคนละแบบ
# แล้วคำที่ควรตรงกันจะกลายเป็นคนละคำ
#
# แก้ปัญหา 3 อย่างที่วัดได้จริงกับคลังนี้
#
# 1. ข้อความไทยที่ "หน้าตาเหมือนกันแต่ไบต์ไม่เหมือนกัน"
#       "เเปลก" (สระ เ สองตัว) กับ "แปลก" (สระ แ ตัวเดียว) มองด้วยตาแยกไม่ออก
#       แต่เป็นคนละสตริง ทำให้ค้นไม่เจอ pythainlp.util.normalize จัดการให้
#
# 2. ชื่อรุ่นและศัพท์อังกฤษที่มียัติภังค์คั่น
#       ตัวตัดคำเดิมใช้ [A-Za-z0-9]+ ทำให้ "ESP32-C5" กลายเป็น ['esp32','c5']
#       คนที่พิมพ์ "ESP32C5" ติดกันจึงหาไม่เจอ ที่นี่เก็บทั้งแบบรวมและแบบแยก
#
# 3. คำทับศัพท์ที่พจนานุกรมของ newmm ไม่รู้จัก
#       วัดแล้ว 15 จาก 43 คำในโดเมนนี้ถูกตัดผิด เช่น
#       "ออสซิลโลสโคป" -> ['ออ','ส','ซิ','ล','โล','ส','โค','ป']  (เศษไร้ความหมาย 8 ชิ้น)
#       "ไมโครคอนโทรลเลอร์" -> ['ไมโคร','คอนโทรลเลอร์']
#       แก้ด้วยการเพิ่มพจนานุกรมเฉพาะโดเมนเข้าไปให้ newmm

import re
import unicodedata

from pythainlp.corpus.common import thai_words
from pythainlp.tokenize import word_tokenize
from pythainlp.util import dict_trie
from pythainlp.util import normalize as thai_normalize

# ศัพท์เฉพาะโดเมนที่ต้องอยู่เป็นคำเดียว
# เพิ่มคำใหม่ได้ตรงนี้ที่เดียว ทั้ง index และ query จะเห็นพร้อมกัน
DOMAIN_WORDS = [
    # ทับศัพท์ที่ newmm ตัดผิด (ยืนยันด้วยการวัดแล้ว)
    "รีสตาร์ต", "ไมโครคอนโทรลเลอร์", "ลิเธียม", "มัลติมิเตอร์", "ออสซิลโลสโคป",
    "เร็กกูเลเตอร์", "บอดเรต", "ดีบัก", "พูลอัพ", "พูลดาวน์", "สวิตชิ่ง",
    "ไจโรสโคป", "เซลลูลาร์", "อีเทอร์เน็ต", "ซับเน็ตมาสก์",
    # ทับศัพท์อื่นในโดเมน ใส่ไว้กันพจนานุกรมเปลี่ยนรุ่นแล้วตัดผิด
    "รีสตาร์ท", "รีเซ็ต", "เฟิร์มแวร์", "เซนเซอร์", "โมดูล", "ไวไฟ", "บลูทูธ", "เกตเวย์",
    "โบรกเกอร์", "แบตเตอรี่", "อนาล็อก", "ดิจิทัล", "ทรานซิสเตอร์", "ไดโอด",
    "รีเลย์", "คอมไพล์", "แฟลช", "พาร์ทิชัน", "บัฟเฟอร์", "อัลตราโซนิก",
    "อินฟราเรด", "โปรโตคอล", "ไลบรารี", "เมทริกซ์", "เอาต์พุต", "อินพุต",
    "ชิป", "บอร์ด", "รีดสวิตช์", "โซลาร์เซลล์", "ไมโครแอมป์", "มิลลิแอมป์",
    "กิโลโอห์ม", "ไมโครฟารัด", "เมกะเฮิรตซ์", "กิโลไบต์", "เมกะไบต์",
]

# ต้อง "รวม" กับพจนานุกรมหลัก ไม่ใช่ส่งเฉพาะคำของเรา
# ถ้าส่งเฉพาะคำของเรา newmm จะไม่รู้จักคำไทยอื่นเลยแล้วเดาเอา
# ทำให้ได้ผลแย่กว่าเดิม เช่น "รีสตาร์ทเองเพราะ" ถูกกลืนเป็นคำเดียว
CUSTOM_DICT = dict_trie(dict_source=set(thai_words()) | set(DOMAIN_WORDS))

# ไม่ตัด stopword ภาษาไทย — ทดลองแล้วว่าทำให้แย่ลง ไม่ใช่ดีขึ้น
#
#   ตัด stopword     MRR 0.4970   (โทเคนเฉลี่ย 50 ตัวต่อเอกสาร)
#   ไม่ตัด           MRR 0.6136   (โทเคนเฉลี่ย 90 ตัวต่อเอกสาร)
#
# เหตุผลสองข้อ หนึ่ง BM25 ลดน้ำหนักคำที่พบทุกที่ด้วย IDF อยู่แล้ว การตัดทิ้งจึง
# ไม่ได้อะไรเพิ่ม แต่ไปทำให้ความยาวเอกสารสั้นลงเกือบครึ่ง ซึ่งกระทบสูตรถ่วง
# ความยาวของ BM25 ทั้งคลัง สองรายการ stopword ของ pythainlp มี 1030 คำและ
# รวมคำอย่าง "ทำไม" "ยังไง" "ต่างกัน" ไว้ด้วย ซึ่งเป็นคำที่บอกว่าผู้ใช้ถามอะไร

THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")

THAI_PATTERN = re.compile(r"[ก-๙]+")
# คำอังกฤษ/ตัวเลข ที่ต่อกันด้วย - _ . ได้ เช่น ESP32-C5, Wi-Fi, esp_err_t, 3.3
LATIN_PATTERN = re.compile(r"[A-Za-z0-9]+(?:[-_.][A-Za-z0-9]+)*")
# รวมเฉพาะยัติภังค์กับขีดล่าง ไม่รวมจุด ไม่งั้น "3.3" จะกลายเป็น "33"
JOIN_INSIDE = re.compile(r"[-_]")
SPLIT_INSIDE = re.compile(r"[-_.]")


def normalize_text(text):
    """
    ปรับข้อความให้อยู่ในรูปเดียวกันก่อนนำไปทำอะไรต่อ

        "เเปลก"      -> "แปลก"        (สระซ้ำ)
        "๓.๓ โวลต์"  -> "3.3 โวลต์"   (เลขไทย)
    """
    text = unicodedata.normalize("NFC", text)
    text = thai_normalize(text)
    text = text.translate(THAI_DIGITS)
    return re.sub(r"\s+", " ", text).strip()


def tokenize(text):
    """
    ตัดข้อความเป็นโทเคนสำหรับ BM25

        "ต่อ ESP32-C5 กับจอ OLED ยังไง"
        -> ['esp32c5', 'esp32', 'c5', 'oled', 'ต่อ', 'จอ']
    """
    text = normalize_text(text)
    tokens = []

    # อังกฤษ/ตัวเลข — เก็บทั้งแบบรวมยัติภังค์และแบบแยกชิ้น
    # เก็บสองแบบเพราะไม่รู้ว่าผู้ใช้จะพิมพ์ "ESP32-C5" หรือ "ESP32C5" มา
    for match in LATIN_PATTERN.finditer(text):
        raw = match.group().lower()
        joined = JOIN_INSIDE.sub("", raw)
        tokens.append(joined)
        if joined != raw:
            tokens.extend(part for part in SPLIT_INSIDE.split(raw) if part)

    # ไทย — ตัดด้วย newmm ที่รู้จักศัพท์โดเมนแล้ว
    for thai_text in THAI_PATTERN.findall(text):
        for word in word_tokenize(thai_text, engine="newmm", custom_dict=CUSTOM_DICT):
            word = word.strip()
            if word:
                tokens.append(word)

    return tokens
